#!/usr/bin/env python3
"""run_all.py - runs every ngspice simulation used in the report and writes ../results/summary.json
Usage:  cd spice && python3 run_all.py
Requires: ngspice (>=42 tested), python3, numpy.   Plots are made by make_plots.py"""
import re, subprocess, json, os, tempfile, shutil, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, '..', 'results')
VDD = 1.8

def run(net, over=None, tag=None, keep_wave=False):
    """run netlist `net` with .param overrides {name:value-string}; returns dict of .meas results"""
    txt = open(os.path.join(HERE, net)).read()
    for k, v in (over or {}).items():
        txt, n = re.subn(r'(^\.param[^\n]*?\b%s=)\S+' % k, r'\g<1>%s' % v, txt, flags=re.M)
        assert n == 1, (k, n)
    if not keep_wave:
        txt = re.sub(r'^wrdata.*\n', '', txt, flags=re.M)
    else:
        txt = txt.replace('../results/', RES + '/')
    d = tempfile.mkdtemp(); p = os.path.join(d, net)
    shutil.copy(os.path.join(HERE, 'models_180nm_L1.lib'), d)
    open(p, 'w').write(txt)
    log = os.path.join(RES, (tag or net.replace('.sp', '')) + '.log')
    r = subprocess.run(['ngspice', '-b', '-o', log, p], capture_output=True, text=True, cwd=d)
    L = open(log).read(); shutil.rmtree(d)
    if re.search(r'(?i)\berror\b|singular|no convergence|timestep too small', L):
        raise RuntimeError('ngspice problem in ' + log)
    m = {k.lower(): float(v) for k, v in re.findall(r'^(\w+)\s+=\s+([-+0-9.eE]+)', L, flags=re.M)}
    return m

def metrics(m, T=20e-9, ncyc=4):
    tp = 0.5 * (m['tplh'] + m['tphl']); Q = m['qtot'] / ncyc; E = Q * VDD
    P = E / T
    return dict(tpLH_ps=m['tplh']*1e12, tpHL_ps=m['tphl']*1e12, Tp_ps=tp*1e12, Q_fC_per_cycle=Q*1e15,
                E_fJ_per_cycle=E*1e15, Pavg_uW=P*1e6, PDP_fJ=P*tp*1e15, Q_stage3_fC=m['q_st3']/ncyc*1e15,
                Vout_max=m['vout_max'], Vout_min=m['vout_min'])

def verify_from_waves():
    """independent check: integrate raw waveforms in python, compare with ngspice .meas; crowbar estimate"""
    out = {}
    for name, f in (('conventional', 'conv_wave.csv'), ('bbm', 'bbm_wave.csv')):
        a = np.loadtxt(os.path.join(RES, f)); t = a[:, 0]
        ncol = a.shape[1] // 2
        cols = [a[:, 2*i+1] for i in range(ncol)]
        itot, i3, i3g = cols[-3], cols[-2], cols[-1]
        w = (t >= 21e-9) & (t <= 101e-9)
        qtot = np.trapezoid(itot[w], t[w]); q3 = np.trapezoid(i3[w], t[w])
        cb = np.minimum(np.clip(i3, 0, None), np.clip(i3g, 0, None))      # crowbar estimate min(iP,iN)
        qcb = np.trapezoid(cb[w], t[w])
        out[name] = dict(qtot_py_fC_per_cycle=qtot/4*1e15, q3_py_fC_per_cycle=q3/4*1e15,
                         crowbar_est_stage3_fC_per_cycle=qcb/4*1e15,
                         ipeak_stage3_uA=float(np.max(i3[w]))*1e6)
    return out

if __name__ == '__main__':
    S = {}
    # 1) baseline: paper's Tp=750ps sizing for both circuits, same model/VDD/T/CL/input
    S['baseline'] = {n: metrics(run(n + '_inverter.sp', keep_wave=True)) for n in ('conventional', 'bbm')}
    mb = run('bbm_inverter.sp', tag='bbm_inverter')   # re-run w/o wave to read BBM-only measures
    S['bbm_nodes'] = dict(A_max=mb['a_max'], A_min=mb['a_min'], B_max=mb['b_max'], B_min=mb['b_min'],
                          t_iso_fall_ps=mb['t_iso_fall_b_to_a']*1e12, t_iso_rise_ps=mb['t_iso_rise_a_to_b']*1e12)
    S['wave_check'] = verify_from_waves()
    # 1b) ABLATION: same BBM sizes, Pt/Nf removed and A,B shorted -> no time skew (= ordinary split-free inverter)
    t = open(os.path.join(HERE, 'bbm_inverter.sp')).read()
    t = re.sub(r'^MPT .*$', 'RSHORT A B 10', t, flags=re.M); t = re.sub(r'^MNF .*\n', '', t, flags=re.M)
    t = t.replace('bbm_wave.csv', 'abl_wave.csv').replace('* bbm_inverter.sp', '* bbm_noskew_ablation.sp (generated by run_all.py)')
    open(os.path.join(HERE, 'bbm_noskew_ablation.sp'), 'w').write(t)
    S['ablation_noskew'] = metrics(run('bbm_noskew_ablation.sp', keep_wave=True))
    # 2) delay-matched sweeps (Q vs Tp), BBM: scale lengths of Pt and P1 ; std: scale lengths of inv1
    def sc(v, s): return '%.1fn' % (v * s)
    S['sweep_std'], S['sweep_bbm'] = [], []
    for s in (0.25, 0.4, 0.55, 0.7, 0.85, 1.0, 1.3, 1.7, 2.2, 3.0):
        o = dict(lp1=sc(370, s), ln1=sc(880, s))
        r = metrics(run('conventional_inverter.sp', o, tag='sweep_std_%g' % s)); r['scale'] = s; S['sweep_std'].append(r)
        o = dict(lp1=sc(740, s), lpt=sc(350, s), lnf=sc(950, s))
        r = metrics(run('bbm_inverter.sp', o, tag='sweep_bbm_%g' % s)); r['scale'] = s; S['sweep_bbm'].append(r)
    # 3) load-capacitance and input-edge sensitivity (baseline sizing)
    S['sweep_cl'] = []
    for cl in ('0.5f', '2f', '5f', '10f'):
        d = {n: metrics(run(n + '_inverter.sp', dict(cl=cl), tag='cl_%s_%s' % (cl, n))) for n in ('conventional', 'bbm')}
        d['cl'] = cl; S['sweep_cl'].append(d)
    S['sweep_edge'] = []
    for te in ('20p', '50p', '200p', '500p'):
        d = {n: metrics(run(n + '_inverter.sp', dict(tedge=te), tag='edge_%s_%s' % (te, n))) for n in ('conventional', 'bbm')}
        d['tedge'] = te; S['sweep_edge'].append(d)
    json.dump(S, open(os.path.join(RES, 'summary.json'), 'w'), indent=1)
    print('done')
